"""
Regenerate the four cross-variant LaTeX tables in results/tables/ from the
stdout logs of the four hybrid scripts (logs/{baseline,gated,forward,phys}.log)
plus the fig13_lcurve_phys.csv data file.

Tables regenerated:
  - table_per_material_by_variant.tex
  - table_ood_per_offset_by_variant.tex
  - table_cross_variant_comparison.tex
  - table_lcurve_phys_sweep.tex

Run after re-executing scripts/run_hybrid{,_gated,_forward,_phys}.py.

    python scripts/regenerate_tex_tables.py
"""

import os
import re
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOGS_DIR = os.path.join(ROOT, "logs")
TABLES_DIR = os.path.join(ROOT, "results", "tables")
DATA_DIR = os.path.join(ROOT, "results", "data")

VARIANTS = ["baseline", "gated", "forward", "phys"]
MATERIALS_ORDER = [
    "water", "vegetation", "metal", "concrete",
    "soil", "asphalt", "human", "tree",
]


def parse_per_material(log_text):
    m = re.search(
        r"In-dist mean \|.T\|:\s*physics=([\d.]+) K\s+hybrid=([\d.]+) K",
        log_text,
    )
    agg = (float(m.group(1)), float(m.group(2))) if m else (None, None)
    per_mat = {}
    for mat in MATERIALS_ORDER:
        mm = re.search(rf"\b{mat}\s+([\d.]+)\s+([\d.]+)\s+\d+", log_text)
        if mm:
            per_mat[mat] = (float(mm.group(1)), float(mm.group(2)))
    return per_mat, agg


def parse_ood(log_text):
    rows = []
    for m in re.finditer(
        r"Offset \+(\d+) K:\s*physics \|.T\|=([\d.]+) K\s+hybrid \|.T\|=([\d.]+) K",
        log_text,
    ):
        rows.append((int(m.group(1)), float(m.group(2)), float(m.group(3))))
    return rows


def parse_kappa_pcts(log_text):
    out = {}
    for q in (10, 25, 50, 75, 90):
        m = re.search(rf"{q}th\s+([\d.]+)\s+([\d.]+)\s+[\d.]+", log_text)
        if m:
            out[q] = (float(m.group(1)), float(m.group(2)))
    return out


def parse_lipschitz_simple(log_text):
    """For baseline/gated/forward: 'Lipschitz upper bound: 1.0012'."""
    m = re.search(r"Lipschitz upper bound:\s*([\d.]+)", log_text)
    return float(m.group(1)) if m else None


def parse_lipschitz_phys(log_text, knee_lambda):
    """For phys: find the L-curve row for the knee lambda."""
    # Pattern: "Training at λ_phys = X ..." then "final_loss=... Lipschitz=Y ..."
    block_re = re.compile(
        r"Training at .*?phys = ([\d.eE+\-]+) \.\.\..*?Lipschitz=([\d.]+)",
        re.DOTALL,
    )
    for m in block_re.finditer(log_text):
        try:
            lam = float(m.group(1))
        except ValueError:
            continue
        if abs(lam - knee_lambda) < 1e-6 * max(abs(knee_lambda), 1.0):
            return float(m.group(2))
    return None


def load_logs(knee_lambda):
    parsed = {}
    for v in VARIANTS:
        with open(os.path.join(LOGS_DIR, f"{v}.log"), encoding="utf-8") as f:
            txt = f.read()
        per_mat, agg = parse_per_material(txt)
        parsed[v] = {
            "per_mat": per_mat,
            "agg": agg,
            "ood": parse_ood(txt),
            "kappa": parse_kappa_pcts(txt),
        }
        if v == "phys":
            parsed[v]["lipschitz"] = parse_lipschitz_phys(txt, knee_lambda)
        else:
            parsed[v]["lipschitz"] = parse_lipschitz_simple(txt)
    return parsed


